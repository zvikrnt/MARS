#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
GKT Baseline for MARS Paper

This is a lightweight Graph-based Knowledge Tracing baseline.

It uses:
1. Same train/test split generated by mars_experiments.py
2. Skill-level graph built from learner skill transitions
3. Graph propagation over skill states
4. GRU update for observed skill-response interaction
5. Next-response prediction using next skill state

Run:

python gkt_baseline.py \
  --train results/assistments_online_final/train_interactions.csv \
  --test results/assistments_online_final/test_interactions.csv \
  --out results/gkt_final \
  --batch_size 256 \
  --epochs 30 \
  --hidden_dim 128 \
  --emb_dim 128 \
  --amp \
  --compile
"""

import argparse
import logging
import random
import time
from pathlib import Path
from collections import Counter

import numpy as np
import pandas as pd
from tqdm import tqdm

import torch
from torch import nn
from torch.utils.data import Dataset, DataLoader

from sklearn.metrics import roc_auc_score, accuracy_score, log_loss, brier_score_loss


# ---------------------------------------------------------------------
# Logging
# ---------------------------------------------------------------------

def setup_logger(out_dir=None):
    logger = logging.getLogger("GKT")
    logger.setLevel(logging.INFO)
    logger.propagate = False

    for handler in list(logger.handlers):
        logger.removeHandler(handler)
        handler.close()

    formatter = logging.Formatter(
        fmt="%(asctime)s | %(levelname)s | %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S"
    )

    console_handler = logging.StreamHandler()
    console_handler.setFormatter(formatter)
    logger.addHandler(console_handler)

    if out_dir is not None:
        Path(out_dir).mkdir(parents=True, exist_ok=True)
        file_handler = logging.FileHandler(Path(out_dir) / "gkt_training.log")
        file_handler.setFormatter(formatter)
        logger.addHandler(file_handler)

    return logger


LOGGER = setup_logger()


class Timer:
    def __init__(self, message):
        self.message = message

    def __enter__(self):
        self.start = time.time()
        LOGGER.info(f"START: {self.message}")
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        elapsed = time.time() - self.start
        if exc_type is None:
            LOGGER.info(f"DONE: {self.message} | Time: {elapsed:.2f} sec")
        else:
            LOGGER.error(f"FAILED: {self.message} | Time: {elapsed:.2f} sec")


