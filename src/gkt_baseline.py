def set_seed(seed=42):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def ensure_dir(path):
    Path(path).mkdir(parents=True, exist_ok=True)


def export_latex_table(df, path, caption="GKT baseline results.", label="tab:gkt_results"):
    tex = df.to_latex(index=False, escape=False)

    tex = tex.replace(
        "\\begin{tabular}",
        f"\\begin{{table}}[t]\n"
        f"\\centering\n"
        f"\\caption{{{caption}}}\n"
        f"\\label{{{label}}}\n"
        f"\\begin{{tabular}}"
    )

    tex = tex.replace(
        "\\end{tabular}",
        "\\end{tabular}\n\\end{table}"
    )

    with open(path, "w", encoding="utf-8") as f:
        f.write(tex)


